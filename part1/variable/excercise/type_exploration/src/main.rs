fn main() {
    let integer: i32 = -42;
    let unsigned: u8 = 200;
    let float: f64 = 3.14159;
    let boolean: bool = true;
    let character: char = '🦀'; // Rust's mascot, Ferris the crab

    println!("i32:   {}", integer);
    println!("u8:    {}", unsigned);
    println!("f64:   {}", float);
    println!("bool:  {}", boolean);
    println!("char:  {}", character);
}
